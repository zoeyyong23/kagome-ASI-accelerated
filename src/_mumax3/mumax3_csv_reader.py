# ---- Process and save every CSV file in a directory ----
def process_all_csv_files(
    input_dir: str,  # directory containing input CSV files
    prefix: str,  # filename prefix to match, e.g. "B_demag" matches "B_demag000042.csv"
    output_dir: str,  # directory to save the processed .npz files
    max_workers: int = 8,  # number of parallel worker processes
    verbose: bool = False,  # print status messages when True
) -> List[str]:
    """
    GOAL:
        Find every CSV file in a directory matching a given prefix, and
        convert each one to a .npz file, in parallel across multiple
        worker processes.

    HOW IT TALKS TO OTHER FILES:
        Called by mumax3_parent_utilities.npz_convert whenever a fresh CSV
        conversion is needed (no valid cached .npz files, or caching
        disabled). Calls process_csv_file (this file) once per matching
        file.

    PARAMETERS:
        input_dir (str): directory containing input CSV files.
        prefix (str): filename prefix to match; only files named exactly
            "{prefix}" followed by six digits and ".csv" are processed.
        output_dir (str): directory to save the processed .npz files;
            created if it does not already exist.
        max_workers (int): number of parallel worker processes.
        verbose (bool): prints status messages (files found, per-file
            outcome) when True. Forwarded to process_csv_file, so per-file
            debug messages appear too.

    RETURNS:
        List[str]: one status message per processed file, in ascending
        index order.

    LIMITATIONS:
        Only filenames matching exactly "{prefix}" + six digits + ".csv"
        are recognized; other numbering widths or naming schemes are
        silently skipped (they simply will not match the pattern and will
        not appear in `files_with_indices`).
    """
    import os  # file path operations
    import re  # filename pattern matching
    import functools  # binding verbose/float_dtype into process_csv_file for the parallel map below
    from concurrent.futures import ProcessPoolExecutor  # parallel processing across files
    if not os.path.isdir(input_dir):  # the input directory must exist
        raise ValueError(f"Input directory does not exist: {input_dir}")
    os.makedirs(output_dir, exist_ok=True)  # ensure the output directory exists

    pattern = re.compile(rf"^{re.escape(prefix)}(\d{{6}})\.csv$")  # matches "{prefix}" + exactly six digits + ".csv"
    files_with_indices = []  # accumulates (index, file_path) pairs for every matching file
    for fname in os.listdir(input_dir):  # scan every file in the input directory
        match = pattern.match(fname)  # check whether this filename matches the expected pattern
        if match:
            index = int(match.group(1))  # the six-digit index, as an integer
            full_path = os.path.join(input_dir, fname)  # full path to this file
            files_with_indices.append((index, full_path))  # record this match
    if not files_with_indices:  # no matching files were found at all
        if verbose:
            print(f"[INFO] process_all_csv_files: no files found in '{input_dir}' matching prefix '{prefix}'.")
        return []
    files_with_indices.sort(key=lambda x: x[0])  # process files in ascending index order
    if verbose:
        print(f"[INFO] process_all_csv_files: found {len(files_with_indices)} file(s) matching prefix '{prefix}'.")
    args_list = [(index, file_path, prefix, output_dir) for index, file_path in files_with_indices]  # one argument tuple per file, for process_csv_file
    worker_fn = functools.partial(process_csv_file, verbose=verbose)  # bind verbose so it is forwarded to every worker call
    with ProcessPoolExecutor(max_workers=max_workers) as executor:  # process every file across up to max_workers processes at once
        results = list(executor.map(worker_fn, args_list))  # run process_csv_file on every file, collecting status messages
    if verbose:
        print(f"[INFO] process_all_csv_files: finished processing {len(results)} file(s).")
    return results


