r"""
File Name: mumax3_csv_reader.py
Author: Connor Sullivan, August Cox
Date: 2025.09.17
Revision: v4

============================================================
PURPOSE
============================================================
Reads CSV files generated by mumax3-convert, converts them into structured
numpy arrays, and saves them as .npz files for efficient storage and
retrieval. Also provides functions to load individual .npz files and
extract specific data arrays.

The expected CSV format is mumax3-convert's stacked layout: a component
(for example, Mx) occupies `height` rows of `width` comma-separated values,
optionally followed by a blank line, then the next component's `height`
rows, and so on for exactly three components (x, y, z). remove_empty_lists
strips any blank-line separators before the row count is split into three
equal blocks, so files with or without those separators are both handled.

============================================================
LIMITATIONS
============================================================
- This module processes data entirely in grid coordinates (cell indices),
  not physical coordinates (nm). Converting to physical coordinates is the
  responsibility of the calling code (region_extraction.py, masking.py),
  which accept a `units` parameter and the grid's cell size for that
  purpose.
"""

from typing import List, Tuple, Dict, Any, Callable, Optional  # type hints used throughout this file's signatures
import numpy as np  # array operations and .npz file handling


# --------------------------
# ---- CSV file reader ----
def read_csv_file(
    file_path: str,  # path to the CSV file
    delimiter: str = ',',  # delimiter used in the CSV file
    encoding: str = 'utf-8',  # file encoding
    raise_errors: bool = False,  # if True, exceptions are raised instead of printed and swallowed
    verbose: bool = False,  # print a status message on success when True
) -> Optional[List[List[str]]]:
    """
    GOAL:
        Read a CSV file and return its contents as a list of rows, each
        row a list of string cell values (not yet converted to numbers).

    HOW IT TALKS TO OTHER FILES:
        Called by process_csv_file (this file) as the first step in
        converting one mumax3 CSV frame to .npz.

    PARAMETERS:
        file_path (str): path to the CSV file.
        delimiter (str): delimiter used in the CSV file.
        encoding (str): file encoding.
        raise_errors (bool): if True, exceptions are raised instead of
            being printed and causing this function to return None.
        verbose (bool): prints a status message describing the number of
            rows read on success when True.

    RETURNS:
        List[List[str]]: the file's contents as rows and columns of string
        values, or None if an error occurred and raise_errors is False.

    LIMITATIONS:
        Returns None on failure rather than raising, unless raise_errors is
        explicitly set to True -- callers that need to distinguish "empty
        file" from "read failed" should set raise_errors=True.
    """
    import csv  # CSV parsing
    import os  # file existence check
    matrix: List[List[str]] = []  # accumulates the parsed rows
    if not os.path.exists(file_path):  # the file must exist before attempting to open it
        message = f"Error: The file '{file_path}' does not exist."
        if raise_errors:
            raise FileNotFoundError(message)
        print(f"[ERROR] read_csv_file: {message}")
        return None
    try:
        with open(file_path, mode='r', newline='', encoding=encoding) as file:  # open the file for reading
            csv_reader = csv.reader(file, delimiter=delimiter)  # parse it as CSV
            matrix = list(csv_reader)  # read every row into memory
    except FileNotFoundError:  # file existed at the check above but disappeared before opening (rare race condition)
        message = f"Error: The file '{file_path}' does not exist."
        if raise_errors:
            raise FileNotFoundError(message)
        print(f"[ERROR] read_csv_file: {message}")
        return None
    except Exception as e:  # any other read failure (permissions, encoding, disk error, etc.)
        message = f"An error occurred while reading '{file_path}': {e}"
        if raise_errors:
            raise
        print(f"[ERROR] read_csv_file: {message}")
        return None
    if verbose:
        print(f"[DEBUG] read_csv_file: read {len(matrix)} row(s) from '{file_path}'.")
    return matrix


# --------------------------
# ---- Remove empty rows (mumax3's block separators) ----
def remove_empty_lists(
    matrix: List[List[Any]],  # list of rows to filter
    is_empty: Optional[Callable[[List[Any]], bool]] = None,  # custom emptiness test; defaults to "falsy"
    verbose: bool = False,  # print how many rows were removed when True
) -> List[List[Any]]:
    """
    GOAL:
        Remove empty rows from a list of rows -- specifically, the
        blank-line separators mumax3-convert places between the x/y/z
        component blocks in its CSV output.

    HOW IT TALKS TO OTHER FILES:
        Called by process_csv_file (this file) immediately after
        read_csv_file, before the remaining rows are split into the three
        x/y/z component blocks.

    PARAMETERS:
        matrix (List[List[Any]]): rows to filter.
        is_empty (Callable, optional): custom function deciding whether a
            row counts as empty. Defaults to Python truthiness (empty list,
            empty string, or None all count as empty).
        verbose (bool): prints the number of rows removed when True.

    RETURNS:
        List[List[Any]]: a new list with empty rows removed.
    """
    if is_empty is None:  # no custom emptiness test given
        is_empty = lambda x: not x  # default: a row is empty if it is falsy
    result = [sublist for sublist in matrix if not is_empty(sublist)]  # keep only non-empty rows
    if verbose:
        print(f"[DEBUG] remove_empty_lists: removed {len(matrix) - len(result)} empty row(s) out of {len(matrix)}.")
    return result


# --------------------------
# ---- Save data arrays to a .npz file ----
def save_to_npz(
    file_index: int,  # index used to format the output filename
    prefix: str,  # prefix used to format the output filename
    data: Dict[str, Any],  # dictionary of arrays to save, e.g. {'x': arr1, 'y': arr2}
    output_dir: str,  # directory to save the file in
    compressed: bool = True,  # whether to use compressed (.npz) or uncompressed storage
    filename_pattern: str = "{prefix}{index:06d}.npz",  # format string; uses {prefix} and {index} placeholders
    verbose: bool = False,  # print the saved file path when True
) -> str:
    """
    GOAL:
        Save a dictionary of arrays to a single .npz file for one frame.

    HOW IT TALKS TO OTHER FILES:
        Called by process_csv_file (this file) once the CSV's x/y/z
        components have been parsed, to write the resulting .npz frame.

    PARAMETERS:
        file_index (int): index used to format the output filename.
        prefix (str): prefix used to format the output filename.
        data (Dict[str, Any]): dictionary of arrays to save; every value
            must have a `.shape` attribute (for example, a numpy array).
        output_dir (str): directory to save the file in; created if it does
            not already exist.
        compressed (bool): True saves as a compressed .npz (smaller file,
            slower to write/read); False saves uncompressed.
        filename_pattern (str): format string for the output filename,
            using {prefix} and {index} placeholders.
        verbose (bool): prints the saved file's path when True.

    RETURNS:
        str: the full path to the saved .npz file.

    LIMITATIONS:
        Raises ValueError if `data` is not a dictionary, if any key is not
        a string, or if any value lacks a `.shape` attribute.
    """
    import os  # file path operations
    if not isinstance(data, dict):  # data must be a dictionary of arrays
        raise ValueError("Data must be a dictionary of arrays.")
    for key, value in data.items():  # validate every key/value pair before writing anything to disk
        if not isinstance(key, str):  # keys must be strings, since they become the .npz's internal array names
            raise ValueError(f"Invalid key in data dictionary: {key}. Keys must be strings.")
        if not hasattr(value, 'shape'):  # values must be array-like
            raise ValueError(f"Invalid value for key '{key}': {value}. Values must be array-like with a 'shape' attribute.")
    os.makedirs(output_dir, exist_ok=True)  # ensure the output directory exists
    filename = os.path.join(output_dir, filename_pattern.format(prefix=prefix, index=file_index))  # build the full output path
    if compressed:  # write as a compressed .npz
        np.savez_compressed(filename, **data)
    else:  # write as an uncompressed .npz
        np.savez(filename, **data)
    if verbose:
        print(f"[DEBUG] save_to_npz: saved '{filename}'.")
    return filename


