# ---- Load full-field data for a single frame, as a named dict ----
def load_full_field_data(npz_directory: str, frame_index: int, prefix: str, verbose: bool = False) -> dict:
    """
    GOAL:
        Load one timestep of full-field data and return it as a dict with
        descriptive keys ('Bx', 'By', 'Bz'), rather than load_npz_frame's
        plain tuple.

    HOW IT TALKS TO OTHER FILES:
        Calls load_npz_frame (this file). Not currently called by any other
        file in this pipeline (mumax3_pipeline_utilities.full_field_magnitude,
        the one function shaped to consume this dict's 'Bx'/'By' keys, is
        itself not currently called either).

    PARAMETERS:
        npz_directory (str): directory containing the .npz files.
        frame_index (int): index of the frame to load.
        prefix (str): filename prefix, e.g. "B_demag".
        verbose (bool): forwarded to load_npz_frame, so its debug message
            appears when True.

    RETURNS:
        dict: {'Bx': ..., 'By': ..., 'Bz': ...}, the same three arrays
        load_npz_frame would return, under descriptive keys.
    """
    Bx, By, Bz = load_npz_frame(  # load this frame's raw x/y/z arrays
        directory=npz_directory,  # folder containing the .npz files
        frame_index=frame_index,  # which frame to load
        keys=('x', 'y', 'z'),  # which arrays to extract
        filename_pattern=f"{prefix}{{:06d}}.npz",  # expected filename format for this prefix
        verbose=verbose,
    )

    return {
        'Bx': Bx,  # x component, under a descriptive key
        'By': By,  # y component, under a descriptive key
        'Bz': Bz  # z component, under a descriptive key
    }
