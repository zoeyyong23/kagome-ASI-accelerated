# ---- Process and save a single CSV file ----
def process_csv_file(
    args: Tuple[int, str, str, str],  # (index, file_path, prefix, output_dir)
    float_dtype: Any = float,  # data type to convert CSV entries into
    verbose: bool = False,  # print a status message when True
) -> str:
    """
    GOAL:
        Process a single mumax3-convert CSV file (stacked x/y/z component
        blocks -- see this file's module-level PURPOSE section) and save it
        as a .npz file. Intended for use with multiprocessing, which is why
        its arguments are bundled into a single tuple rather than passed
        individually -- see this function's LIMITATIONS.

    HOW IT TALKS TO OTHER FILES:
        Called by process_all_csv_files (this file), once per CSV file,
        potentially from a separate worker process. Calls read_csv_file,
        remove_empty_lists, and save_to_npz (all this file).

    PARAMETERS:
        args (Tuple[int, str, str, str]): (index, file_path, prefix,
            output_dir) -- index and prefix are used to name the output
            file, file_path is the CSV to read, output_dir is where the
            .npz is written.
        float_dtype (Any): data type to convert every CSV cell into.
        verbose (bool): prints a status message describing the outcome when
            True.

    RETURNS:
        str: a status message indicating success, or the reason a file was
        skipped or failed.

    LIMITATIONS:
        Arguments are bundled into a single tuple (rather than individual
        parameters) specifically so this function can be used directly with
        multiprocessing's map-style APIs (see process_all_csv_files), which
        pass one argument per call. Errors are reported as a returned status
        string rather than raised, since an exception raised inside a
        worker process would otherwise need additional handling to surface
        clearly to the caller.
    """
    index, file_path, prefix, output_dir = args  # unpack the bundled arguments
    import os  # file existence check
    if not os.path.exists(file_path):  # nothing to process if the source file is missing
        return f"Skipped (file not found): {file_path}"
    try:
        raw_matrix = read_csv_file(file_path, verbose=verbose)  # read the raw CSV rows
        if not raw_matrix:  # the file was empty or unreadable
            return f"Skipped (empty or unreadable): {file_path}"
        raw_matrix = remove_empty_lists(raw_matrix, verbose=verbose)  # strip mumax3's blank-line block separators
        try:
            raw_matrix = [[float_dtype(cell) for cell in row] for row in raw_matrix]  # convert every cell to a number
        except ValueError as e:  # at least one cell was not numeric
            return f"Skipped (non-numeric data): {file_path} - {e}"
        total_rows = len(raw_matrix)  # total row count, expected to split evenly into three components
        if total_rows % 3 != 0:  # the file does not look like a valid stacked x/y/z layout
            return f"Skipped (invalid row count): {file_path}"
        height = total_rows // 3  # number of rows per component
        matrix_x = raw_matrix[0:height]  # first block: x component
        matrix_y = raw_matrix[height:2 * height]  # second block: y component
        matrix_z = raw_matrix[2 * height:3 * height]  # third block: z component
        save_to_npz(file_index=index, prefix=prefix, data={'x': np.array(matrix_x), 'y': np.array(matrix_y), 'z': np.array(matrix_z)}, output_dir=output_dir, verbose=verbose)  # write the parsed components to disk
        if verbose:
            print(f"[INFO] process_csv_file: processed '{file_path}'.")
        return f"Processed: {file_path}"
    except Exception as e:  # any unexpected failure during parsing/saving
        return f"Failed: {file_path} - {e}"


