# ---- Load a single .npz frame ----
def load_npz_frame(
    directory: str,  # directory containing the .npz files
    frame_index: int,  # index of the frame to load
    keys: Tuple[str, str, str] = ('x', 'y', 'z'),  # which arrays to extract from the .npz file
    filename_pattern: Optional[str] = "B_demag{:06d}.npz",  # filename format string with one positional placeholder for frame_index
    verbose: bool = False,  # print the loaded file path when True
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    GOAL:
        Load a single .npz file from disk and extract the requested keys.

    HOW IT TALKS TO OTHER FILES:
        Called by frame_pipeline.process_single_frame to load one frame's
        raw data before region extraction/masking, and by
        load_full_field_data (this file).

    PARAMETERS:
        directory (str): directory containing the .npz files.
        frame_index (int): index of the frame to load.
        keys (Tuple[str, str, str]): the three keys to extract from the
            .npz file.
        filename_pattern (str, optional): format string for the filename;
            must contain one positional placeholder for frame_index.
            Defaults to "B_demag{:06d}.npz" if not given.
        verbose (bool): prints the resolved filename when True.

    RETURNS:
        Tuple[np.ndarray, np.ndarray, np.ndarray]: the arrays corresponding
        to `keys`, in the same order.

    LIMITATIONS:
        Raises FileNotFoundError if the expected file does not exist, and
        KeyError if any requested key is missing from the file -- neither
        failure is caught or converted into a status message here (unlike
        process_csv_file, which is designed to be run in bulk and report
        per-file failures rather than raise).
    """
    import os  # file path operations
    if filename_pattern is None:  # no explicit pattern given
        filename_pattern = "B_demag{:06d}.npz"  # default pattern
    filename = os.path.join(directory, filename_pattern.format(frame_index))  # build the full path to this frame's file
    if verbose:
        print(f"[DEBUG] load_npz_frame: loading '{filename}'.")

    if not os.path.exists(filename):  # the expected file must exist
        raise FileNotFoundError(f"File not found: {filename}")

    with np.load(filename) as data:  # open the .npz file
        try:
            arrays = tuple(data[key] for key in keys)  # extract every requested key
        except KeyError as e:  # at least one requested key was not present in the file
            missing_key = e.args[0]  # which key was missing
            raise KeyError(f"Key '{missing_key}' not found in file '{filename}'.")
    return arrays


